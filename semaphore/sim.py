"""Mesoscopic traffic simulator for an R x C grid of signalised intersections.

A 1 x 1 grid is the isolated intersection of Part A (4 legs, 3 lanes, two
phases, straight-through traffic as in the paper); a 3 x 3 grid is Part B.

Model (1 s time step, every vehicle tracked individually):
  * Each approach of each intersection is fed by one *link* of fixed length.
    A vehicle entering a link reaches the stop line after the free-flow travel
    time, then joins a FIFO queue (point queue at the stop line).
  * Link storage is finite (length * lanes / jam spacing). A link that is full
    cannot accept vehicles, so the upstream approach is blocked even on green
    -> queue spillback emerges naturally between neighbours.
  * During green (after the start-up lost time) an approach discharges at the
    saturation flow; the head vehicle moves to the link of its next movement
    (straight / right / left with fixed probabilities) or leaves the network.
  * Vehicles at the grid boundary are generated by a Poisson process (synthetic
    or driven by real sensor data); if the entry link is full they wait in an
    unbounded entry buffer, and that wait counts toward their trip delay.
  * Signals: two phases (N-S, E-W), intergreen with no discharge.
    Adaptive controllers are asked for a green extension dt at g_min and then
    every sample_time seconds while green ("rolling" extension); the total
    extension is capped at e_max. Fixed controllers use preset green times.
"""
from __future__ import annotations

import random
from collections import deque

import numpy as np

from .config import Config, DEFAULT

SIDES = ("N", "E", "S", "W")
SIDE_IDX = {s: i for i, s in enumerate(SIDES)}
HEAD_VEC = {"S": (1, 0), "N": (-1, 0), "E": (0, 1), "W": (0, -1)}
ARRIVE_SIDE = {"S": "N", "N": "S", "E": "W", "W": "E"}   # heading -> side it arrives on
HEADING_FROM = {v: k for k, v in ARRIVE_SIDE.items()}     # side -> heading of its traffic
RIGHT = {"S": "W", "W": "N", "N": "E", "E": "S"}
LEFT = {"S": "E", "E": "N", "N": "W", "W": "S"}
PHASE_SIDES = ((0, 2), (1, 3))   # phase 0 = N,S ; phase 1 = E,W (side indices)


class Vehicle:
    __slots__ = ("t_gen", "t_stop", "next_heading", "ff", "stops", "wait")

    def __init__(self, t_gen):
        self.t_gen = t_gen
        self.t_stop = 0
        self.next_heading = None
        self.ff = 0
        self.stops = 0
        self.wait = 0


class Link:
    __slots__ = ("node", "side", "tt", "storage", "transit", "queue", "credit",
                 "out", "is_entry", "buffer", "heading", "qsum", "blocked_green")

    def __init__(self, node, side, tt, storage, is_entry):
        self.node, self.side, self.tt, self.storage = node, side, tt, storage
        self.transit = deque()
        self.queue = deque()
        self.credit = 0.0
        self.out = {}            # heading -> Link or None (exit)
        self.is_entry = is_entry
        self.buffer = deque()    # entry buffer (only used if is_entry)
        self.heading = HEADING_FROM[side]
        self.qsum = 0.0
        self.blocked_green = 0

    @property
    def occupancy(self):
        return len(self.transit) + len(self.queue)


class Signal:
    __slots__ = ("ctrl", "phase", "state", "t_start", "ext_used", "t_next", "t_end",
                 "t_y_end", "green_log")

    def __init__(self, ctrl, t0=0, phase=0):
        self.ctrl = ctrl
        self.phase = phase
        self.green_log = []   # (t_start, duration, phase) for diagnostics
        self._start_green(t0)

    def _start_green(self, t):
        self.state = "G"
        self.t_start = t
        self.ext_used = 0.0
        if self.ctrl.kind == "fixed":
            self.t_next = None
            self.t_end = t + self.ctrl.green(self.phase)
        else:
            self.t_next = t + self.ctrl.g_min
            self.t_end = None


class GridSim:
    def __init__(self, rows, cols, controllers, cfg: Config = DEFAULT, turn_probs=None,
                 seed=0, record_timeseries=True, exit_caps=None):
        self.R, self.C, self.cfg = rows, cols, cfg
        # Optional downstream bottleneck beyond the grid edge: {heading: veh/s}
        # per exit point (e.g. a lane drop on the arterials leaving eastwards).
        # A value may be (veh/s, t_from, t_to) for a temporary incident.
        self.exit_caps = {h: (v if isinstance(v, tuple) else (v, 0, 10 ** 9))
                          for h, v in dict(exit_caps or {}).items()}
        rd = cfg.road
        self.tt = rd.travel_time_s
        self.storage = rd.storage_veh
        self.cap = rd.sat_flow
        self.lanes = rd.lanes
        self.horizon = rd.detector_horizon_s
        tp = rd.turn_probs if turn_probs is None else turn_probs
        self.p_straight, self.p_right = tp[0], tp[0] + tp[1]
        self.rand = random.Random(seed)
        self.np_rng = np.random.default_rng(seed)
        self.record_ts = record_timeseries

        # links[(r, c)][side_idx]
        self.links = {}
        self.entries = []
        for r in range(rows):
            for c in range(cols):
                row = []
                for s in SIDES:
                    h = HEADING_FROM[s]
                    dr, dc = HEAD_VEC[h]
                    up = (r - dr, c - dc)
                    is_entry = not (0 <= up[0] < rows and 0 <= up[1] < cols)
                    L = Link((r, c), s, self.tt, self.storage, is_entry)
                    row.append(L)
                    if is_entry:
                        self.entries.append(L)
                self.links[(r, c)] = row
        for (r, c), row in self.links.items():
            for L in row:
                for h in ("N", "E", "S", "W"):
                    dr, dc = HEAD_VEC[h]
                    nr, nc = r + dr, c + dc
                    if 0 <= nr < rows and 0 <= nc < cols:
                        L.out[h] = self.links[(nr, nc)][SIDE_IDX[ARRIVE_SIDE[h]]]
                    else:
                        L.out[h] = None
        self.nodes = sorted(self.links)
        if not isinstance(controllers, dict):
            controllers = {n: controllers(n) for n in self.nodes}
        self.signals = {n: Signal(controllers[n], t0=0,
                                  phase=getattr(controllers[n], "start_phase", 0))
                        for n in self.nodes}
        for n in self.nodes:   # fixed-time offsets
            ctrl = controllers[n]
            off = getattr(ctrl, "offset", 0)
            if off:
                sig = self.signals[n]
                sig.t_end = sig.t_start + max(1, ctrl.green(sig.phase) - off)

    # ------------------------------------------------------------------
    def _choose(self, h):
        u = self.rand.random()
        if u < self.p_straight:
            return h
        return RIGHT[h] if u < self.p_right else LEFT[h]

    def _enter_link(self, veh, L, t):
        veh.t_stop = t + L.tt
        veh.ff += L.tt
        veh.next_heading = self._choose(L.heading)
        L.transit.append(veh)

    def observe(self, node, t):
        """What the detectors/cameras at one intersection report."""
        row = self.links[node]
        q = [len(L.queue) for L in row]
        av = []
        lim = t + self.horizon
        for L in row:
            n = 0
            for v in L.transit:
                if v.t_stop <= lim:
                    n += 1
                else:
                    break
            av.append(n)
        down = []
        for L in row:
            nxt = L.out[L.heading]
            down.append(0.0 if nxt is None else nxt.occupancy / nxt.storage)
        return {"phase": self.signals[node].phase, "queue": q, "av": av, "down_occ": down,
                "lanes": self.lanes, "t": t}

    # ------------------------------------------------------------------
    def run(self, duration, entry_rates, warmup=None, hooks=None):
        """entry_rates: array (n_entries,) veh/s constant, or (n_entries, duration)."""
        cfg = self.cfg
        sc = cfg.signal
        warm = cfg.warmup_s if warmup is None else warmup
        rates = np.asarray(entry_rates, float)
        if rates.ndim == 1:
            rates = np.repeat(rates[:, None], duration, axis=1)
        arrivals = self.np_rng.poisson(rates[:, :duration])

        waits, wait_node, delays, stops = [], [], [], []
        exits = 0
        ts_queue = []
        all_links = [L for n in self.nodes for L in self.links[n]]
        node_of = {id(L): i for i, n in enumerate(self.nodes) for L in self.links[n]}
        cap = self.cap
        startup = sc.startup_lost
        T = sc.sample_time
        e_max = sc.e_max
        inter = sc.intergreen
        node_ids = {n: i for i, n in enumerate(self.nodes)}
        exit_credit = {(n, h): 1.0 for n in self.nodes for h in self.exit_caps}

        for t in range(duration):
            rec = t >= warm
            # 1. boundary demand
            for k, L in enumerate(self.entries):
                for _ in range(arrivals[k, t]):
                    L.buffer.append(Vehicle(t))
                while L.buffer and L.occupancy < L.storage:
                    self._enter_link(L.buffer.popleft(), L, t)
            # 2. stop-line arrivals
            for L in all_links:
                tr = L.transit
                while tr and tr[0].t_stop <= t:
                    L.queue.append(tr.popleft())
            # 3. signals
            for n in self.nodes:
                sig = self.signals[n]
                if sig.state == "G":
                    if sig.t_next is not None and t >= sig.t_next:
                        dt = float(sig.ctrl.decide(self.observe(n, t)))
                        remaining = e_max - sig.ext_used
                        d = min(max(dt, 0.0), remaining)
                        if d >= T and remaining > T:
                            sig.ext_used += T
                            sig.t_next = t + T
                        else:
                            sig.ext_used += d
                            sig.t_next = None
                            sig.t_end = t + int(round(d))
                    if sig.t_end is not None and t >= sig.t_end:
                        sig.green_log.append((sig.t_start, t - sig.t_start, sig.phase))
                        sig.state = "Y"
                        sig.t_y_end = t + inter
                elif t >= sig.t_y_end:
                    sig.phase = 1 - sig.phase
                    sig._start_green(t)
            # 4. discharge
            for key in exit_credit:
                c, t0, t1 = self.exit_caps[key[1]]
                c = c if t0 <= t < t1 else 1e6
                exit_credit[key] = min(exit_credit[key] + c, 1.0 + c)
            for n in self.nodes:
                sig = self.signals[n]
                if sig.state != "G" or t - sig.t_start < startup:
                    continue
                row = self.links[n]
                ni = node_ids[n]
                for si in PHASE_SIDES[sig.phase]:
                    L = row[si]
                    qd = L.queue
                    if not qd:
                        L.credit = 0.0
                        continue
                    L.credit += cap
                    while L.credit >= 1.0 and qd:
                        v = qd[0]
                        nxt = L.out[v.next_heading]
                        if nxt is None and (n, v.next_heading) in exit_credit:
                            if exit_credit[(n, v.next_heading)] < 1.0:
                                if rec:
                                    L.blocked_green += 1
                                L.credit = min(L.credit, 1.0)
                                break
                            exit_credit[(n, v.next_heading)] -= 1.0
                        elif nxt is not None and nxt.occupancy >= nxt.storage:
                            if rec:
                                L.blocked_green += 1
                            L.credit = min(L.credit, 1.0)
                            break
                        qd.popleft()
                        L.credit -= 1.0
                        w = t - v.t_stop
                        v.wait += w
                        if w >= 2:
                            v.stops += 1
                        if rec:
                            waits.append(w)
                            wait_node.append(ni)
                        if nxt is None:
                            if rec:
                                exits += 1
                                delays.append(t - v.t_gen - v.ff)
                                stops.append(v.stops)
                        else:
                            self._enter_link(v, nxt, t)
                    if not qd:
                        L.credit = 0.0
            # 5. statistics
            if rec:
                tot = 0
                for L in all_links:
                    q = len(L.queue)
                    L.qsum += q
                    tot += q
                if self.record_ts and t % 60 == 0:
                    ts_queue.append((t, tot, sum(len(L.buffer) for L in self.entries)))
            if hooks:
                for h in hooks:
                    h(self, t)

        span = max(1, duration - warm)
        # Vehicles still in the network at the end are counted with their wait
        # / delay so far; otherwise a gridlocked run would look *better*
        # because its worst vehicles never finish (survivorship bias).
        unfinished = []
        for i, n in enumerate(self.nodes):
            for L in self.links[n]:
                for v in L.queue:
                    if v.t_stop >= warm:
                        waits.append(duration - v.t_stop)
                        wait_node.append(i)
                for v in list(L.queue) + list(L.transit):
                    if v.t_gen >= warm:
                        unfinished.append(max(0, duration - v.t_gen - v.ff))
                for v in L.buffer:
                    if v.t_gen >= warm:
                        unfinished.append(duration - v.t_gen)
        delays_all = np.asarray(delays + unfinished, float)
        waits = np.asarray(waits, float)
        wait_node = np.asarray(wait_node, int)
        delays = np.asarray(delays, float)
        node_q = np.array([sum(L.qsum for L in self.links[n]) / (4 * span) for n in self.nodes])
        node_w = np.array([waits[wait_node == i].mean() if np.any(wait_node == i) else np.nan
                           for i in range(len(self.nodes))])
        in_system = sum(L.occupancy + len(L.buffer) for L in all_links)
        return {
            "avg_queue": float(np.mean(node_q)),                 # veh per approach
            "avg_wait": float(waits.mean()) if len(waits) else np.nan,   # s per stop-line passage
            "p95_wait": float(np.percentile(waits, 95)) if len(waits) else np.nan,
            "avg_delay": float(delays.mean()) if len(delays) else np.nan,  # s per trip
            "p95_delay": float(np.percentile(delays, 95)) if len(delays) else np.nan,
            "avg_delay_all": float(delays_all.mean()) if len(delays_all) else np.nan,
            "p95_delay_all": float(np.percentile(delays_all, 95)) if len(delays_all) else np.nan,
            "unfinished": len(unfinished),
            "worst_node_wait": float(np.nanmax(node_w)),
            "stops_per_trip": float(np.mean(stops)) if stops else np.nan,
            "throughput_vph": exits * 3600.0 / span,
            "blocked_green_s": float(sum(L.blocked_green for L in all_links)) / max(1, len(self.nodes)) * 3600.0 / span,
            "in_system_end": int(in_system),
            "node_queue": node_q.tolist(),
            "node_wait": node_w.tolist(),
            "ts_queue": ts_queue,
            "_waits": waits,
            "_delays": delays,
        }
